-- Support an ordered product queue while keeping bids isolated per auction lot.

alter table public.auctions
  add column if not exists sort_order bigint generated by default as identity;

comment on column public.auctions.sort_order is
  'Stable order in which auction lots are presented and started.';

create unique index if not exists auctions_sort_order_unique
  on public.auctions (sort_order);

create index if not exists auctions_status_sort_order_idx
  on public.auctions (status, sort_order);

-- Foreign-key columns are not indexed automatically by PostgreSQL.
create index if not exists participants_user_id_idx
  on public.participants (user_id);

create index if not exists bids_participant_id_idx
  on public.bids (participant_id);

-- Clean up any pre-existing duplicate active rows deterministically before the
-- single-active-lot invariant is enforced.
with ranked_active as (
  select id, row_number() over (order by sort_order, id) as active_rank
  from public.auctions
  where status = 'active'
)
update public.auctions as auction
set status = 'ended',
    ends_at = coalesce(auction.ends_at, now())
from ranked_active
where auction.id = ranked_active.id
  and ranked_active.active_rank > 1;

create unique index if not exists auctions_single_active_idx
  on public.auctions (status)
  where status = 'active';

-- Starting a lot must end the previous one and activate the target in one
-- transaction. The advisory lock serializes concurrent administrator actions.
create or replace function public.activate_auction(p_auction_id uuid)
returns setof public.auctions
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_status public.auction_status;
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('public.activate_auction', 0)
  );

  select auction.status into v_status
  from public.auctions as auction
  where auction.id = p_auction_id
  for update;

  if not found then
    raise exception 'Auction lot not found.';
  end if;

  if v_status <> 'upcoming' then
    raise exception 'Only an upcoming auction lot can be started.';
  end if;

  update public.auctions
  set status = 'ended',
      ends_at = coalesce(ends_at, now())
  where status = 'active';

  return query
  update public.auctions
  set status = 'active',
      starts_at = now(),
      ends_at = null
  where id = p_auction_id
  returning *;
end;
$$;

revoke all on function public.activate_auction(uuid) from public, anon, authenticated;
grant execute on function public.activate_auction(uuid) to service_role;
